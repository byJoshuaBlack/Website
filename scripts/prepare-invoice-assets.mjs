// Packs the invoice's fonts and logo into src/store/invoice-assets.ts, since the Worker cannot read
// files. Run `npm run invoice:assets` after changing a font or the logo.
import { readFile, writeFile } from "node:fs/promises";
import sharp from "sharp";

const PINE = { r: 0, g: 79, b: 73 };
const root = new URL("../", import.meta.url);
const read = (path) => readFile(new URL(path, root));

// The artwork is a mask on the site; here it becomes pine on transparent, trimmed and 800px wide.
const alpha = await sharp(await read("src/assets/brand/jb-horizontal.png")).trim().resize({ width: 800 }).extractChannel("alpha").raw().toBuffer({ resolveWithObject: true });
const { width, height } = alpha.info;
const logo = await sharp({ create: { width, height, channels: 3, background: PINE } })
  .joinChannel(alpha.data, { raw: { width, height, channels: 1 } })
  .png({ compressionLevel: 9 })
  .toBuffer();

const assets = {
  interRegular: await read("src/assets/fonts/Inter-Regular.ttf"),
  tuskerMedium: await read("src/assets/fonts/TuskerGrotesk-3500Medium.otf"),
  logo,
};

const lines = [
  "// Generated by scripts/prepare-invoice-assets.mjs; do not edit by hand.",
  `export const logoSize = { width: ${width}, height: ${height} };`,
  ...Object.entries(assets).map(([name, bytes]) => `export const ${name} = "${bytes.toString("base64")}";`),
  "",
];
await writeFile(new URL("src/store/invoice-assets.ts", root), lines.join("\n"));
console.log(Object.entries(assets).map(([name, bytes]) => `${name}: ${Math.round(bytes.length / 1024)} KB`).join(", "), `· logo ${width}×${height}`);
